using System.Text;

namespace Elonia.DataManager
{
    public sealed class CodeWriter
    {
        public const string GENERATED_MARKER = "// <auto-generated>";

        private const string INDENT = "    ";

        private readonly StringBuilder _builder = new StringBuilder();
        private int _depth;

        public void Line(string text)
        {
            for (int index = 0; index < _depth; index++)
            {
                _builder.Append(INDENT);
            }

            _builder.Append(text).Append('\n');
        }

        public void Line()
        {
            _builder.Append('\n');
        }

        public void Open()
        {
            Line("{");
            _depth++;
        }

        public void Close()
        {
            _depth--;
            Line("}");
        }

        public void FileHeader(string source)
        {
            Line(GENERATED_MARKER);
            Line("//     Elonia.DataManager가 엑셀에서 만든 파일이다. 직접 고치지 않는다.");
            Line("//     고치려면 엑셀을 고친 뒤 도구를 다시 실행한다.");
            Line("//     원본: " + source);
            Line("// </auto-generated>");
            Line("#nullable enable");
            Line();
        }

        public void Summary(string text)
        {
            string singleLine = text.Replace("\r", " ").Replace("\n", " ").Trim();
            if (singleLine.Length == 0)
            {
                return;
            }

            string escaped = singleLine.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");
            Line("/// <summary>" + escaped + "</summary>");
        }

        public override string ToString()
        {
            return _builder.ToString();
        }
    }
}
